import * as assert from 'assert';
import * as fs from 'fs';
import * as path from 'path';
import { testSysdir } from './testSysdir';

/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/no-explicit-any */
const root = path.resolve(__dirname, '../../..');
const gen = require(path.join(root, 'scripts', 'gen-connect-schema.js'));
const yaml = require('js-yaml');
const Ajv = require('ajv');

const SYSDIR = testSysdir('connectSchema', 'docs/UG_GAMSCONNECT.html') ?? '';
const haveSysdir = SYSDIR !== '';
const schema = JSON.parse(fs.readFileSync(path.join(root, 'schemas', 'connect', 'connect.schema.json'), 'utf8'));
const validate = new Ajv({ strict: false }).compile(schema);
const ok = (text: string): boolean => validate(yaml.load(text)) as boolean;

function agent(name: string): any {
  return schema.items.oneOf.find((b: any) => b.title === name).properties[name];
}
const noDesc = (): undefined => undefined;

describe('Connect schema generator (rule mapping)', () => {
  it('maps type, allowed, default, nullable, min/max', () => {
    const s = gen.convertRule({ type: 'string', default: 'all', allowed: ['all', 'first'], nullable: true }, 'x', noDesc);
    assert.deepStrictEqual(s, { type: ['string', 'null'], default: 'all', enum: ['all', 'first', null] });
    assert.deepStrictEqual(gen.convertRule({ type: 'integer', min: 0, max: 20 }, 'x', noDesc), { type: 'integer', minimum: 0, maximum: 20 });
    assert.deepStrictEqual(gen.convertRule({ type: ['integer', 'string'] }, 'x', noDesc).type, ['integer', 'string']);
  });

  it('maps nested dict (required only without default, unknown keys rejected) and list items', () => {
    const s = gen.convertRule(
      { type: 'list', schema: { type: 'dict', schema: { name: { type: 'string', required: true }, n: { type: 'string', default: null, required: true, nullable: true } } } },
      'x',
      noDesc,
    );
    assert.strictEqual(s.type, 'array');
    assert.deepStrictEqual(s.items.required, ['name']);
    assert.strictEqual(s.items.additionalProperties, false);
    assert.deepStrictEqual(s.items.properties.n.type, ['string', 'null']);
  });

  it('maps oneof (with nullable adding a null branch) and excludes', () => {
    const s = gen.convertRule({ nullable: true, oneof: [{ type: 'string', allowed: ['all'] }, { type: 'list' }] }, 'x', noDesc);
    assert.strictEqual(s.oneOf.length, 3);
    assert.deepStrictEqual(s.oneOf[2], { type: 'null' });
    const f = gen.convertFields({ a: { type: 'string', nullable: true, excludes: ['b'] }, b: { type: 'string', nullable: true } }, 'x', noDesc, false);
    assert.strictEqual(f.allOf.length, 1);
  });

  it('rejects Cerberus rules without a mapping', () => {
    assert.throws(() => gen.convertRule({ type: 'string', regex: '^a' }, 'x', noDesc), /unsupported Cerberus rule 'regex'/);
    assert.throws(() => gen.convertRule({ type: 'complex' }, 'x', noDesc), /unsupported type/);
  });

  it('reads only anchor ids from the docs', () => {
    const html = '<h2><a class="anchor" id="FOO"></a>Foo</h2><p>text</p><p><a class="anchor" id="FOO_FILE"></a><b>file:</b></p>';
    assert.deepStrictEqual([...gen.parseAnchors(html)], ['FOO', 'FOO_FILE']);
  });
});

describe('Connect schema (committed, generated from the official schemas)', () => {
  it('has one branch per agent and a provenance comment', () => {
    assert.strictEqual(schema.$schema, 'http://json-schema.org/draft-07/schema#');
    assert.match(schema.$comment, /GENERATED by scripts\/gen-connect-schema\.js from GAMS 54\./);
    assert.strictEqual(schema.items.oneOf.length, 18);
    assert.ok(schema.items.oneOf.every((b: any) => b.required.length === 1 && b.additionalProperties === false));
  });

  it('GDXWriter: required file, enum, nested symbols, docs', () => {
    const a = agent('GDXWriter');
    assert.deepStrictEqual(a.required, ['file']);
    assert.deepStrictEqual(a.properties.duplicateRecords.enum, ['all', 'first', 'last', 'none']);
    assert.strictEqual(a.properties.trace.type, 'integer');
    assert.strictEqual(a.properties.symbols.oneOf[1].items.required[0], 'name');
    assert.strictEqual(a.properties.file.description, undefined);
    assert.strictEqual(a.properties.file.markdownDescription, '[Documentation](https://www.gams.com/latest/docs/UG_GAMSCONNECT.html#GDXWRITER_FILE)');
  });

  it('ExcelReader: min/max and excludes', () => {
    const a = agent('ExcelReader');
    assert.strictEqual(a.properties.columnDimension.maximum, 20);
    assert.ok(a.allOf.length >= 2);
  });

  it('accepts valid files and rejects invalid ones', () => {
    assert.ok(ok('- GDXWriter:\n    file: out.gdx\n    symbols: all\n'));
    assert.ok(ok('- CSVReader:\n    file: a.csv\n    name: a\n    indexColumns: [1, 2]\n    valueColumns: [3]\n'));
    assert.ok(!ok('- GDXWriter:\n    symbols: all\n'), 'missing required file');
    assert.ok(!ok('- GDXWriter:\n    file: out.gdx\n    duplicateRecords: sometimes\n'), 'bad enum');
    assert.ok(!ok('- GDXWriter:\n    file: out.gdx\n    bogus: 1\n'), 'unknown option');
    assert.ok(!ok('- NoSuchAgent:\n    file: out.gdx\n'), 'unknown agent');
    assert.ok(!ok('- GDXWriter:\n    file: out.gdx\n  CSVWriter:\n    file: a.csv\n'), 'two agents in one item');
    assert.ok(!ok('- ExcelReader:\n    file: a.xlsx\n    columnDimension: 21\n    symbols:\n      - name: x\n'), 'max');
    assert.ok(!ok('- Filter:\n    name: p\n    labelFilters:\n      - dimension: 1\n        keep: [a]\n        regex: a\n'), 'excludes');
  });

  (haveSysdir ? it : it.skip)('is identical to a fresh generation from GAMS_SYSDIR', () => {
    const fresh = gen.generate(SYSDIR);
    assert.deepStrictEqual(fresh, schema);
  });
});

/** YAML of the embedded-Connect examples and the plain agent examples of the offline docs. */
function docExamples(): string[] {
  const html = fs.readFileSync(path.join(SYSDIR, 'docs', 'UG_GAMSCONNECT.html'), 'utf8');
  const un = (s: string): string =>
    s.replace(/<[^>]*>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
  const out: string[] = [];
  for (const m of html.matchAll(/<pre><code class="language-gams">([\s\S]*?)<\/code><\/pre>/g)) {
    for (const e of un(m[1]).matchAll(/\$onEmbeddedCode Connect:[^\n]*\n([\s\S]*?)\n\$offEmbeddedCode/gi)) out.push(e[1]);
  }
  for (const m of html.matchAll(/<pre class="fragment">([\s\S]*?)<\/pre>/g)) {
    const t = un(m[1]);
    if (/^- [A-Za-z]+:/.test(t)) out.push(t.replace(/%MYFILENAME%/g, 'distance.csv'));
  }
  return out;
}

(haveSysdir ? describe : describe.skip)('Connect schema vs. official documentation examples', function () {
  this.timeout(20000);
  it('every YAML example in UG_GAMSCONNECT.html validates', () => {
    const ex = docExamples();
    assert.ok(ex.length >= 25, `only ${ex.length} examples found`);
    for (const t of ex) {
      const doc = yaml.load(t);
      assert.ok(validate(doc), `${t.split('\n').slice(0, 3).join(' | ')}: ${JSON.stringify(validate.errors?.slice(0, 2))}`);
    }
  });
});
