/*
 * GAMS Connect standalone runner (no vscode imports).
 * `gamsconnect <YAMLFile> [key1=value1 ...]` (sysdir script `gamsconnect` -> connectdriver.py; usage text in
 * $GAMS_SYSDIR/docs/UG_GAMSCONNECT.html "gamsconnect"). Key/value pairs replace `%key%` in the YAML text
 * (case-insensitive) before it is parsed (connectdriver.py).
 */
import { spawn } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { GamsProcess } from '../run/gamsProcess';

// eslint-disable-next-line @typescript-eslint/no-require-imports
const yaml = require('js-yaml') as { load(text: string): unknown };

/** Sysdir script name. Windows name (gamsconnect.exe) is an assumption: no Windows sysdir was available. */
export function connectExecutableName(platform: NodeJS.Platform = process.platform): string {
  return platform === 'win32' ? 'gamsconnect.exe' : 'gamsconnect';
}

/** Arguments after the executable: the YAML file (absolute or relative to cwd) and the substitutions. */
export function buildConnectArgs(yamlFile: string, substitutions: string[] = []): string[] {
  return [yamlFile, ...substitutions.map((s) => s.trim()).filter((s) => /^[^=\s][^=]*=/.test(s))];
}

/** connectdriver.py: `re.sub(f"%{k}%", v.replace("\\", "\\\\"), flags=IGNORECASE)` for every key. */
export function applySubstitutions(text: string, substitutions: string[]): string {
  for (const kv of substitutions) {
    const i = kv.indexOf('=');
    if (i <= 0) continue;
    const key = kv.substring(0, i).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    text = text.replace(new RegExp(`%${key}%`, 'gi'), () => kv.substring(i + 1));
  }
  return text;
}

/**
 * Absolute paths of the GDX files written by `GDXWriter` agents of a Connect file (option `file`, relative paths
 * resolve against `baseDir` = the working directory of the run). Agents generated by PythonCode are not seen.
 */
export function findGdxOutputs(text: string, baseDir: string, substitutions: string[] = []): string[] {
  let doc: unknown;
  try {
    doc = yaml.load(applySubstitutions(text, substitutions));
  } catch {
    return [];
  }
  const items = Array.isArray(doc) ? doc : [doc];
  const out: string[] = [];
  for (const item of items) {
    if (!item || typeof item !== 'object') continue;
    const opts = (item as Record<string, unknown>)['GDXWriter'];
    const file = opts && typeof opts === 'object' ? (opts as Record<string, unknown>)['file'] : undefined;
    if (typeof file !== 'string' || !file) continue;
    const abs = path.resolve(baseDir, file);
    if (!out.includes(abs)) out.push(abs);
  }
  return out;
}

/** Outputs that exist and were written at or after `since` (ms epoch). */
export function writtenSince(files: string[], since: number): string[] {
  return files.filter((f) => {
    try {
      return fs.statSync(f).mtimeMs >= since;
    } catch {
      return false;
    }
  });
}

/** `gamsconnect` process: GamsProcess machinery (env, process group, graceful stop) with another executable. */
export class ConnectProcess extends GamsProcess {
  override get exePath(): string {
    return path.join(this.sysdir, connectExecutableName());
  }

  /**
   * The script is a shell wrapper around python: signal the whole process group (SIGINT -> KeyboardInterrupt in
   * Python). On Windows a plain taskkill (no /F) is sent; UNTESTED, the GAMS message-window interrupt of
   * GamsProcess does not apply to Python.
   */
  override interrupt(): void {
    const pid = this.pid;
    if (!pid || pid <= 1 || !this.running) return;
    if (process.platform === 'win32') {
      spawn('taskkill', ['/T', '/PID', String(pid)], { detached: true, stdio: 'ignore', windowsHide: true }).unref();
      return;
    }
    try {
      process.kill(-pid, 'SIGINT');
    } catch {
      try { process.kill(pid, 'SIGINT'); } catch { /* already gone */ }
    }
  }
}
