const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)([-_.].*)?$/i;

function licenseTexts(dir) {
  let names = [];
  try { names = fs.readdirSync(dir); } catch { return []; }
  const out = [];
  for (const n of names.sort()) {
    const p = path.join(dir, n);
    if (LICENSE_FILE.test(n) && fs.statSync(p).isFile()) out.push(fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n').trim());
    else if (/^licen[sc]es?$/i.test(n) && fs.statSync(p).isDirectory()) out.push(...licenseTexts(p));
  }
  return out;
}

/** Group entries {name, version, license, texts[]} by license text. */
function render(title, pkgs, note) {
  pkgs.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  let md = `## ${title}\n\n${note}\n\n| Package | Version | License |\n| --- | --- | --- |\n`;
  for (const p of pkgs) md += `| ${p.name} | ${p.version} | ${String(p.license).replace(/\|/g, '/')} |\n`;
  const groups = new Map();
  const missing = [];
  for (const p of pkgs) {
    if (!p.texts.length) { missing.push(p); continue; }
    for (const t of new Set(p.texts)) {
      const h = crypto.createHash('sha1').update(t).digest('hex');
      if (!groups.has(h)) groups.set(h, { text: t, pkgs: [] });
      groups.get(h).pkgs.push(`${p.name}@${p.version}`);
    }
  }
  md += '\n';
  for (const g of groups.values()) md += `### ${g.pkgs.join(', ')}\n\n\`\`\`\n${g.text}\n\`\`\`\n\n`;
  if (missing.length) {
    md += '### Packages without a license file\n\nThe following packages ship no license file; their license is as declared in the table above.\n\n';
    md += missing.map((p) => `- ${p.name}@${p.version}${p.author ? ' (author: ' + p.author + ')' : ''}`).join('\n') + '\n\n';
  }
  return md;
}

async function npmPackages() {
  const dirs = new Set();
  for (const [entry, platform] of BUNDLES) {
    const r = await esbuild.build({
      entryPoints: [path.join(root, entry)], bundle: true, write: false, metafile: true, logLevel: 'silent',
      format: platform === 'node' ? 'cjs' : 'iife', platform, target: 'node20', external: ['vscode'],
    });
    for (const f of Object.keys(r.metafile.inputs)) {
      const m = /^(.*?node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(f);
      if (m) dirs.add(m[1]);
    }
  }
  const pkgs = new Map();
  for (const d of dirs) {
    const dir = path.join(root, d);
    const j = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const lic = typeof j.license === 'string' ? j.license : j.license?.type ?? (j.licenses ?? []).map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
    pkgs.set(`${j.name}@${j.version}`, { name: j.name, version: j.version, license: lic || 'UNKNOWN', texts: licenseTexts(dir), author: typeof j.author === 'string' ? j.author : j.author?.name }); 
  }
  return [...pkgs.values()];
}

function rustCrates() {
  const md = JSON.parse(execFileSync(cargo, ['metadata', '--format-version', '1', '--locked', '--manifest-path', path.join(root, 'server/Cargo.toml')], { maxBuffer: 1 << 28 }).toString());
  const byId = new Map(md.packages.map((p) => [p.id, p]));
  const nodes = new Map(md.resolve.nodes.map((n) => [n.id, n]));
  const start = md.packages.find((p) => p.name === 'gams-lsp');
  const seen = new Set();
  const stack = [start.id];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id).deps) if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
  const members = new Set(md.workspace_members);
  return [...seen].filter((id) => !members.has(id)).map((id) => {
    const p = byId.get(id);
    return { name: p.name, version: p.version, license: p.license ?? p.license_file ?? 'UNKNOWN', texts: licenseTexts(path.dirname(p.manifest_path)) };
  });
}

(async () => {
  const npm = await npmPackages();
  const rust = rustCrates();
  let out = `# Third-party notices

This extension (eunseong-park.vscode-gams) is licensed under GPL-3.0-or-later. It includes or is derived from the
software listed below. Generated by \`scripts/gen-notices.js\` (\`npm run gen:notices\`); do not edit.

`;
  out += FIXED + '\n';
  out += render('npm packages bundled into dist/', npm, 'Runtime dependencies bundled by esbuild into the extension and webview bundles.');
  out += render('Rust crates compiled into the gams-lsp language server', rust, 'Normal (non-dev, non-build) dependencies of `gams-lsp` from `server/Cargo.lock`, for all target platforms.');
  fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.replace(/\n{3,}/g, '\n\n'));
  console.log(`THIRD_PARTY_NOTICES.md: ${npm.length} npm packages, ${rust.length} crates`);
})().catch((e) => { console.error(e); process.exit(1); });
